'use strict';

const {
  captureRecording,
  getUserError,
  MAX_RECORDING_SECONDS,
} = require('../../lib/webCapture');

module.exports = {
  name: 'screenrecord',
  aliases: ['webrecord'],
  category: 'general',
  description: `Record a public webpage for up to ${MAX_RECORDING_SECONDS} seconds`,
  usage: `.screenrecord <website URL> [seconds, max ${MAX_RECORDING_SECONDS}]`,
  reactions: { start: '🎥' },

  async execute(sock, m, { args, reply }) {
    const input = [...args];
    let duration = MAX_RECORDING_SECONDS;
    if (input.length > 1 && /^\d+$/.test(input[input.length - 1])) {
      duration = Number(input.pop());
    }
    const url = input.join(' ').trim();

    if (!url) {
      return reply(
        `⚠️ *Screen recording failed*\n\n` +
        `Please provide a website URL.\n` +
        `Example: .screenrecord https://example.com 5\n` +
        `Maximum recording length: ${MAX_RECORDING_SECONDS} seconds.`,
      );
    }

    let video;
    try {
      video = await captureRecording(url, duration);
    } catch (error) {
      console.error(`[screenrecord] ${error.code || 'CAPTURE_ERROR'}:`, error.cause || error);
      return reply(`⚠️ *Screen recording failed*\n\n${getUserError(error, 'screenrecord')}`);
    }

    try {
      await sock.sendMessage(m.chat, {
        video,
        mimetype: 'video/mp4',
        caption: '> Screen recording generated by CODEX AI',
      }, { quoted: m });
    } catch (error) {
      console.error('[screenrecord] DELIVERY_ERROR:', error);
      return reply('⚠️ *Screen recording delivery failed*\n\nThe video was created, but WhatsApp could not send it. Please try again.');
    }
  },
};
